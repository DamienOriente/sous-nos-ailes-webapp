import { z } from "zod";

/** Version of the legal texts (CGU + privacy policy) accepted at sign-up. */
export const POLICY_VERSION = "2026-10";

export const PASSWORD_MIN_LENGTH = 10;
export const PASSWORD_MAX_LENGTH = 128;

export const emailSchema = z.string().trim().toLowerCase().max(254, "Adresse e-mail trop longue.").pipe(z.email("Adresse e-mail invalide."));

export const passwordSchema = z
  .string()
  .min(PASSWORD_MIN_LENGTH, `Le mot de passe doit contenir au moins ${PASSWORD_MIN_LENGTH} caractères.`)
  .max(PASSWORD_MAX_LENGTH, `Le mot de passe ne peut pas dépasser ${PASSWORD_MAX_LENGTH} caractères.`);

const nameSchema = z.string().trim().min(1, "Ce champ est requis.").max(80, "80 caractères maximum.");

export const signUpSchema = z.object({
  firstName: nameSchema,
  lastName: nameSchema,
  email: emailSchema,
  password: passwordSchema,
  acceptTerms: z.literal(true, { message: "Vous devez accepter les conditions pour créer un compte." }),
  next: z.string().optional(),
});
export type SignUpInput = z.infer<typeof signUpSchema>;

export const signInSchema = z.object({
  email: emailSchema,
  password: z.string().min(1, "Mot de passe requis."),
  rememberMe: z.boolean().default(true),
});
export type SignInInput = z.infer<typeof signInSchema>;

export const totpCodeSchema = z
  .string()
  .trim()
  .regex(/^\d{6}$/, "Le code comporte 6 chiffres.");

/**
 * Backup codes are generated by better-auth as `xxxxx-xxxxx` (10 mixed-case
 * alphanumerics) and compared verbatim: we only normalise spacing and the dash.
 */
export const backupCodeSchema = z
  .string()
  .trim()
  .transform((v) => v.replace(/[\s-]/g, ""))
  .pipe(z.string().regex(/^[A-Za-z0-9]{10}$/, "Code de secours invalide."))
  .transform((v) => `${v.slice(0, 5)}-${v.slice(5)}`);

export const changePasswordSchema = z
  .object({
    currentPassword: z.string().min(1, "Mot de passe actuel requis."),
    newPassword: passwordSchema,
    confirmPassword: z.string(),
    revokeOtherSessions: z.boolean().default(true),
  })
  .refine((v) => v.newPassword === v.confirmPassword, { path: ["confirmPassword"], message: "Les deux mots de passe ne correspondent pas." })
  .refine((v) => v.newPassword !== v.currentPassword, { path: ["newPassword"], message: "Le nouveau mot de passe doit être différent de l'actuel." });
export type ChangePasswordInput = z.infer<typeof changePasswordSchema>;

export const resetPasswordSchema = z
  .object({
    token: z.string().min(1, "Lien invalide."),
    newPassword: passwordSchema,
    confirmPassword: z.string(),
  })
  .refine((v) => v.newPassword === v.confirmPassword, { path: ["confirmPassword"], message: "Les deux mots de passe ne correspondent pas." });

/**
 * Open-redirect guard: only a relative path starting with a single "/" is
 * accepted ("//evil.com", "/\evil.com", "javascript:" and absolute URLs are not).
 */
export function safeNextPath(value: string | null | undefined, fallback = "/app"): string {
  if (!value) return fallback;
  if (value.length > 2048) return fallback;
  if (!value.startsWith("/")) return fallback;
  if (value.startsWith("//") || value.startsWith("/\\")) return fallback;
  if (/[\u0000-\u001f\s]/.test(value)) return fallback;
  // Never bounce back to the auth pages themselves (would loop).
  if (/^\/(connexion|inscription|mot-de-passe-oublie|reinitialiser|verification-email)(\/|\?|$)/.test(value)) return fallback;
  return value;
}

export type PasswordStrength = { score: 0 | 1 | 2 | 3 | 4; label: string; hints: string[] };

const COMMON_PASSWORDS = new Set(["password", "motdepasse", "azertyuiop", "qwertyuiop", "1234567890", "0123456789", "abcdefghij", "iloveyou12", "soleil1234"]);

/**
 * Heuristic strength indicator shown while typing. It is a UX aid only: the
 * server enforces length, better-auth hashes with scrypt.
 */
export function passwordStrength(password: string): PasswordStrength {
  const hints: string[] = [];
  if (password.length === 0) return { score: 0, label: "", hints: [`Au moins ${PASSWORD_MIN_LENGTH} caractères.`] };

  let points = 0;
  if (password.length >= PASSWORD_MIN_LENGTH) points += 1;
  else hints.push(`Encore ${PASSWORD_MIN_LENGTH - password.length} caractère(s).`);
  if (password.length >= 14) points += 1;
  const classes = [/[a-z]/, /[A-Z]/, /\d/, /[^A-Za-z0-9]/].filter((re) => re.test(password)).length;
  if (classes >= 2) points += 1;
  if (classes >= 3) points += 1;
  if (classes < 3) hints.push("Mélangez lettres, chiffres et symboles.");
  if (/^(.)\1+$/.test(password) || /^(?:0123|1234|2345|3456|4567|5678|6789|abcd|azer|qwer)/i.test(password)) {
    points = Math.min(points, 1);
    hints.push("Évitez les suites évidentes.");
  }
  if (COMMON_PASSWORDS.has(password.toLowerCase())) {
    points = 0;
    hints.push("Ce mot de passe est trop courant.");
  }
  if (password.length < PASSWORD_MIN_LENGTH) points = Math.min(points, 1);

  const score = Math.max(0, Math.min(4, points)) as PasswordStrength["score"];
  const label = ["Trop faible", "Faible", "Correct", "Bon", "Excellent"][score] ?? "";
  return { score, label, hints };
}

/** Human-readable mapping of better-auth error codes shown on the auth pages. */
export function authErrorMessage(code: string | undefined, status?: number): string {
  if (status === 429) return "Trop de tentatives. Patientez un instant avant de réessayer.";
  switch (code) {
    case "USER_ALREADY_EXISTS":
    case "USER_ALREADY_EXISTS_USE_ANOTHER_EMAIL":
      return "Un compte existe déjà avec cette adresse. Connectez-vous ou réinitialisez votre mot de passe.";
    case "EMAIL_NOT_VERIFIED":
      return "Confirmez d'abord votre adresse e-mail : nous venons de vous renvoyer le lien.";
    case "PASSWORD_TOO_SHORT":
      return `Le mot de passe doit contenir au moins ${PASSWORD_MIN_LENGTH} caractères.`;
    case "PASSWORD_TOO_LONG":
      return `Le mot de passe ne peut pas dépasser ${PASSWORD_MAX_LENGTH} caractères.`;
    case "INVALID_PASSWORD":
      return "Mot de passe actuel incorrect.";
    case "INVALID_TOKEN":
      return "Ce lien n'est plus valide. Demandez-en un nouveau.";
    case "TOKEN_EXPIRED":
      return "Ce lien a expiré. Demandez-en un nouveau.";
    case "INVALID_CODE":
    case "INVALID_BACKUP_CODE":
      return "Code incorrect. Vérifiez et réessayez.";
    case "TOO_MANY_ATTEMPTS_REQUEST_NEW_CODE":
    case "ACCOUNT_TEMPORARILY_LOCKED":
      return "Trop de codes incorrects. Patientez quelques minutes avant de réessayer.";
    case "INVALID_TWO_FACTOR_COOKIE":
      return "Votre session de vérification a expiré. Reconnectez-vous.";
    case "BANNED_USER":
      return "Ce compte est suspendu. Contactez le support si vous pensez qu'il s'agit d'une erreur.";
    case "INVALID_EMAIL_OR_PASSWORD":
    case "INVALID_EMAIL":
    case "USER_NOT_FOUND":
    case "CREDENTIAL_ACCOUNT_NOT_FOUND":
      // Deliberately generic: never reveal whether the e-mail exists.
      return "Identifiants incorrects.";
    default:
      return "Une erreur est survenue. Réessayez dans un instant.";
  }
}
