export const blockSchema = z.discriminatedUnion("type", [
  heroBlockSchema,
  aboutBlockSchema,
  servicesBlockSchema,
  pricingBlockSchema,
  galleryBlockSchema,
  testimonialsBlockSchema,
  faqBlockSchema,
  contactBlockSchema,
  availabilityBlockSchema,
  socialBlockSchema,
  ctaQuoteBlockSchema,
  trustBlockSchema,
  zoneBlockSchema,
]);

export type Block = z.infer<typeof blockSchema>;
export type BlockType = Block["type"];
export type BlockOf<T extends BlockType> = Extract<Block, { type: T }>;

export const BLOCK_TYPES = blockSchema.options.map((o) => o.shape.type.value) as BlockType[];

export const pageContentSchema = z
  .array(blockSchema)
  .max(30)
  .refine((blocks) => new Set(blocks.map((b) => b.id)).size === blocks.length, "Identifiants de section en double.")
  .refine((blocks) => blocks.filter((b) => b.type === "hero").length <= 1, "Une seule section d'en-tête est possible.");
export type PageContent = z.infer<typeof pageContentSchema>;

// ── Theme ───────────────────────────────────────────────────────────────────
export const RADIUS_OPTIONS = ["sharp", "soft", "round"] as const;
export type RadiusOption = (typeof RADIUS_OPTIONS)[number];

export const themeSchema = z.object({
  palette: z.string().regex(/^[a-z0-9-]{2,40}$/).optional(),
  accent: hexColor.optional(),
  fontPairing: z.string().regex(/^[a-z0-9-]{2,40}$/).optional(),
  radius: z.enum(RADIUS_OPTIONS).optional(),
});
export type PageTheme = z.infer<typeof themeSchema>;

export const seoFieldsSchema = z.object({
  seoTitle: safeText(70).nullable().optional(),
  seoDescription: safeText(170).nullable().optional(),
});

// ── Parsing helpers ─────────────────────────────────────────────────────────
export type ParseResult<T> = { ok: true; value: T } | { ok: false; issues: string[] };

export function parseContent(input: unknown): ParseResult<PageContent> {
  const r = pageContentSchema.safeParse(input);
  return r.success ? { ok: true, value: r.data } : { ok: false, issues: r.error.issues.map((i) => `${i.path.join(".")}: ${i.message}`) };
}

export function parseTheme(input: unknown): ParseResult<PageTheme> {
  const r = themeSchema.safeParse(input ?? {});
  return r.success ? { ok: true, value: r.data } : { ok: false, issues: r.error.issues.map((i) => `${i.path.join(".")}: ${i.message}`) };
}

/**
 * Upgrades stored content from an older schema version to the current one.
 * Version 1 is the first schema; the function already exists so that a future
 * version only needs a new `case`. Unknown versions are rejected explicitly.
 */
export function migrateContent(content: unknown, fromVersion: number): { content: unknown; schemaVersion: number } {
  if (fromVersion > SCHEMA_VERSION) throw new Error(`Unknown page schema version ${fromVersion}`);
  let current = content;
  let version = fromVersion;
  while (version < SCHEMA_VERSION) {
    switch (version) {
      case 0:
        // Pre-schema prototypes: keep an array as is (validated downstream), anything else becomes an empty page.
        current = Array.isArray(current) ? current : [];
        break;
      // case 1: current = migrateV1toV2(current); break;
      default:
        throw new Error(`No migration from schema version ${version}`);
    }
    version += 1;
  }
  return { content: current, schemaVersion: SCHEMA_VERSION };
}

export function newBlockId(): string {
  const alphabet = "abcdefghijklmnopqrstuvwxyz0123456789";
  let out = "b";
  for (let i = 0; i < 9; i += 1) out += alphabet[Math.floor(Math.random() * alphabet.length)];
  return out;
}

/** Plain-text projection of a rich text tree (search, SEO description, length checks). */
export function richTextToPlain(body: RichText): string {
  return body
    .map((b) => (b.type === "paragraph" ? b.children.map((c) => c.text).join("") : b.items.map((it) => it.map((c) => c.text).join("")).join(" ")))
    .join("\n")
    .trim();
}

export function plainToRichText(text: string): RichText {
  return text
    .split(/\n{2,}|\n/)
    .map((p) => p.trim())
    .filter(Boolean)
    .map((p) => ({ type: "paragraph" as const, children: [{ text: p }] }));
}

